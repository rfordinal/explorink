#!/usr/bin/env python3
"""Bake the map's zoom side-hint glyphs into src/components/icons/side_hint_icons.h.

    python3 scripts/gen_side_hint_icons.py

Replaces MapActivity::drawZoomSideHints()'s plain-text "+"/"--" with Lucide
`plus`/`minus` icons -- the text glyphs were barely visible at the side-hint
box's font size, and doubling the hyphen ("--") was a workaround for that, not
a design choice (MapActivity.cpp's own comment on the doubling, and
firmware/explorink/docs/map-observation-mode.md's "zoom side hints" finding).
Maintainer's call, 2026-10-18: Lucide plus/minus, single glyph, visibly bold.

Same `freeink::Icon` output format as scripts/gen_home_icons.py (1bpp MSB
first, bit 0 = ink, opticalCenterY), same threshold 110, same rsvg-convert /
cairosvg fallback.

**Drawn with GfxRenderer::drawMono1bpp(), the ordinary map-screen convention**
(home_icons.h's own icons use it too) -- NOT drawIcon(). A first cut of this
feature used drawIcon() here on the theory that this box's TEXT already goes
through an equivalent extra rotation (drawTextRotated90CW()) for sitting
sideways on the screen edge, so an icon should match it. **Wrong, confirmed on
hardware 2026-10-20**: drawIcon()'s quarter turn is the same rotation that
already made the plain-text "-" illegible in the first place (a horizontal
stroke read as a thin vertical sliver) -- it is not a convention to replicate,
it is the bug. The box's own border is drawn in plain, unrotated coordinates
and reads correctly; a plain `drawMono1bpp()` icon does too, with no rotation
needed at all. (`+` looked identical either way in testing, since a plus is
rotation-symmetric -- only `-` exposed the mistake, by coming out as a
vertical bar.)

Stroke width is bumped from Lucide's default 2 to BOLD_STROKE before
rasterising: at ICON_SIZE (24px, chosen to clear the side-hint box's own
30px-wide content area, BaseTheme.h's `sideButtonHintsWidth`), the default
stroke reads thin on the panel -- the same "weak glyph" problem the side-hint
font already needed a bold cut for (map-observation-mode.md, "the zoom side
hints never checked the ladder ends, and were weaker than the pan hints").
"""
import io
import os
import re
import shutil
import subprocess
import sys

from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LUCIDE = os.path.join(REPO, "freeink-sdk/libs/assets/Icons/lucide/icons")
OUT = os.path.join(REPO, "src/components/icons/side_hint_icons.h")

THRESHOLD = 110
ICON_SIZE = 24
BOLD_STROKE = 3.2

ICONS = [
    ("plus", "plus"),
    ("minus", "minus"),
]


def rasterise(svg_path, size):
    svg_text = open(svg_path, "r", encoding="utf-8").read()
    svg_text = re.sub(r'stroke-width="[\d.]+"', f'stroke-width="{BOLD_STROKE}"', svg_text)
    if shutil.which("rsvg-convert"):
        png = subprocess.run(
            ["rsvg-convert", "-w", str(size), "-h", str(size), "/dev/stdin"],
            input=svg_text.encode("utf-8"),
            capture_output=True,
            check=True,
        ).stdout
    else:
        import cairosvg

        png = cairosvg.svg2png(bytestring=svg_text.encode("utf-8"), output_width=size, output_height=size)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    flat = Image.new("RGBA", img.size, (255, 255, 255, 255))
    flat.paste(img, mask=img.split()[3])
    return flat.convert("L")


def pack(img):
    """-> (bytes, opticalCenterY). 1 = transparent, 0 = ink, MSB first."""
    width, height = img.size
    pixels = img.load()
    data = []
    sum_y = 0
    count = 0
    for y in range(height):
        for x_byte in range(0, width, 8):
            byte = 0
            for bit in range(8):
                x = x_byte + bit
                white = 1
                if x < width and pixels[x, y] < THRESHOLD:
                    white = 0
                    sum_y += y
                    count += 1
                byte |= white << (7 - bit)
            data.append(byte)
    return data, (round(sum_y / count) if count else height // 2)


def ident(name):
    return re.sub(r"[^A-Za-z0-9]", "_", name)


def emit(alias, img, note):
    data, centre = pack(img)
    width, height = img.size
    bits = f"icon_{ident(alias)}_bits"
    body = ", ".join(f"0x{b:02X}" for b in data)
    return [
        f"// {note}",
        f"static const uint8_t {bits}[] = {{{body}}};",
        f"static const freeink::Icon icon_{ident(alias)} = "
        f"{{{width}, {height}, {centre}, {bits}}};",
        "",
    ]


def main():
    out = [
        "#pragma once",
        "",
        "#include <Icon.h>",
        "",
        "#include <cstdint>",
        "",
        "// Generated by scripts/gen_side_hint_icons.py. Do not edit.",
        f"// {ICON_SIZE}px, stroke-width {BOLD_STROKE} (Lucide's default is 2 -- bumped",
        "// for legibility at this size). Drawn with GfxRenderer::drawMono1bpp(), the",
        "// ordinary map-screen convention -- see this script's own module docstring",
        "// for why an earlier cut tried drawIcon() here and why that was wrong.",
        "",
    ]
    for alias, lucide in ICONS:
        svg = os.path.join(LUCIDE, lucide + ".svg")
        if not os.path.exists(svg):
            sys.exit(f"missing svg for '{alias}': {svg}")
        out += emit(alias, rasterise(svg, ICON_SIZE), f"{alias}  (lucide: {lucide})")

    with open(OUT, "w") as handle:
        handle.write("\n".join(out))
    if shutil.which("clang-format"):
        subprocess.run(["clang-format", "-i", OUT], check=True)
    else:
        print("warning: clang-format not found -- run it on the output before committing")
    print(f"wrote {OUT}: {len(ICONS)} icons")


if __name__ == "__main__":
    main()
