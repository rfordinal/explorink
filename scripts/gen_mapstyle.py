#!/usr/bin/env python3
"""
Generate the compiled MapStyle instance from data/mapstyle.json.

MapStyleDefaults.h is a build product, like MapModeMaskDefaults.h and
lib/I18n/I18nKeys.h -- gitignored, regenerated on every build (wired as a
pre: step in platformio.ini, and as a CMake custom command for the host
build in test/CMakeLists.txt). data/mapstyle.json is the source: it lives in
this repo and is the device's definitive style, so the firmware builds
standalone with nothing read from outside it.

Because the host build regenerates from the same file, editing the style in
mapbuilder's webapp and rebuilding test/map_preview shows the change without
flashing anything. See docs/mapstyle.json.md.

Usage:
    python3 scripts/gen_mapstyle.py [style_path [output_path]]

Defaults: data/mapstyle.json -> src/activities/map/MapStyleDefaults.h.
"""
import json
import os
import sys

# The tile format's own class_id enum (mapbuilder/class_spec.py, mirrored in
# MapClassEnum.h). Duplicated here for the same reason gen_mode_masks.py
# duplicates it: nothing outside this repo may be read to build this repo.
_CLASS_ID = {
    "unknown": 0,
    "motorway": 1,
    "trunk": 2,
    "primary": 3,
    "secondary": 4,
    "tertiary": 5,
    "unclassified": 6,
    "residential": 7,
    "living_street": 8,
    "service": 9,
    "pedestrian": 10,
    "track": 11,
    "bridleway": 12,
    "cycleway": 13,
    "footway": 14,
    "path": 15,
    "steps": 16,
    "construction": 17,
    "ferry": 18,
    "railway": 19,
    "aerialway": 20,
}

# MapClassEnum.h's kClassEnumSlots -- the array length MapStyle declares.
_CLASS_SLOTS = 32

# The area layers' own small class enums (MapAreaClass.h, mirroring
# mapbuilder/water_class.py and landuse_class.py). Not slots in the road enum:
# a record's layer id already says which vocabulary its class byte belongs to.
_WATER_CLASS = {"unknown": 0, "river": 1, "stream": 2, "lake": 3}
_LANDUSE_CLASS = {"forest": 1, "built_up": 2}
_WATER_SLOTS = 4
_LANDUSE_SLOTS = 4

_HEADER_NOTE = "Generated by scripts/gen_mapstyle.py from data/mapstyle.json. Do not hand-edit."


def _round_px(value, what):
    """Style lengths are floats; the canvas takes int pixels. Round half up.

    Python's round() is banker's rounding, which would turn a 2.5px casing
    into 2 and a 3.5px one into 4 -- not what a style author reading the
    file would predict.
    """
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        sys.exit(f"gen_mapstyle.py: {what}: expected a number, got {value!r}")
    if value < 0:
        sys.exit(f"gen_mapstyle.py: {what}: negative length {value}")
    return int(value + 0.5)


def road_widths(style):
    """Returns (widths, casings), each kClassEnumSlots long, indexed by class_id.

    A class with no rule of its own gets layers.roads.default's width, which
    is what the laptop-side renderer does (mapbuilder/style.py resolve_rule).
    A hidden class, and every reserved enum slot, gets width 0 -- MapRenderer
    skips those without drawing.
    """
    roads = style.get("layers", {}).get("roads")
    if roads is None:
        sys.exit("gen_mapstyle.py: layers.roads missing")

    widths = [0] * _CLASS_SLOTS
    casings = [0] * _CLASS_SLOTS
    patterns = ["Solid"] * _CLASS_SLOTS
    dashes = [0] * _CLASS_SLOTS
    gaps = [0] * _CLASS_SLOTS
    if not roads.get("enabled", True):
        print("gen_mapstyle.py: layers.roads.enabled is false -- no roads will be drawn")
        return widths, casings, patterns, dashes, gaps

    default_width = _round_px(roads.get("default", {}).get("width", 1), "layers.roads.default.width")
    for class_id in _CLASS_ID.values():
        widths[class_id] = max(default_width, 1)

    for index, rule in enumerate(roads.get("rules", [])):
        classes = rule.get("match", {}).get("class", [])
        for name in classes:
            if name not in _CLASS_ID:
                sys.exit(f"gen_mapstyle.py: layers.roads.rules[{index}]: unknown class '{name}'")
            if rule.get("hidden", False):
                widths[_CLASS_ID[name]] = 0
                casings[_CLASS_ID[name]] = 0
                patterns[_CLASS_ID[name]] = "Solid"
                dashes[_CLASS_ID[name]] = 0
                gaps[_CLASS_ID[name]] = 0
                continue
            width = _round_px(rule.get("width", default_width), f"layers.roads.rules[{index}].width")
            # A visible class must stay visible. Rounding 0.4px to 0 would
            # silently delete a road class that the style file draws.
            width = max(width, 1)
            if width > 255:
                sys.exit(f"gen_mapstyle.py: class '{name}' width {width}px does not fit a uint8_t")
            widths[_CLASS_ID[name]] = width

            casing = _round_px(rule.get("casing_px", 0), f"layers.roads.rules[{index}].casing_px")
            # Two casings plus at least one white pixel between them, or there
            # is no white left and the "casing" is just a solid black line
            # drawn the slow way, in two passes.
            if casing > 0 and 2 * casing >= width:
                casing = 0
                print(f"gen_mapstyle.py: class '{name}': casing_px leaves no white inside a {width}px "
                      f"road -- drawing it solid instead")
            casings[_CLASS_ID[name]] = casing
            (patterns[_CLASS_ID[name]], dashes[_CLASS_ID[name]],
             gaps[_CLASS_ID[name]]) = _dash(rule, f"layers.roads.rules[{index}]")

    if not any(widths):
        sys.exit("gen_mapstyle.py: every road class resolves to width 0 -- a style that draws no "
                 "roads at all is never what a style file means")
    return widths, casings, patterns, dashes, gaps


def puck(style):
    """(radius, ring, arrow) for layers.position, in px.

    Disabled means radius 0, which MapRenderer reads as "no disc, arrow only".
    The arrow is kept either way: a position that draws nothing is never what
    a style file means.
    """
    position = style.get("layers", {}).get("position", {})
    arrow = _round_px(position.get("arrow_px", 28), "layers.position.arrow_px")
    if not position.get("enabled", True):
        print("gen_mapstyle.py: layers.position.enabled is false -- arrow only, no puck disc")
        return 0, 0, arrow
    radius = _round_px(position.get("puck_radius_px", 0), "layers.position.puck_radius_px")
    ring = _round_px(position.get("ring_px", 0), "layers.position.ring_px")
    if radius and ring >= radius:
        sys.exit(f"gen_mapstyle.py: layers.position.ring_px {ring} leaves no white disc inside "
                 f"puck_radius_px {radius}")
    for name, value in (("puck_radius_px", radius), ("ring_px", ring), ("arrow_px", arrow)):
        if value > 255:
            sys.exit(f"gen_mapstyle.py: layers.position.{name} {value}px does not fit a uint8_t")
    return radius, ring, arrow


# mapstyle.json's hatch strings are matplotlib's. Only the character matters
# here; the repeat count ("XXXX") is a matplotlib density knob, and density on
# the device comes from hatch_spacing_px, in device pixels like every other
# length. Maps to MapAreaFill::Pattern.
# mapstyle.json's `pattern` finally reaches the device. Dash length in device
# pixels; the gap matches it. "dotted" is a short dash, not a single pixel --
# one pixel on and one off is a grey line at arm's length, not a dotted one.
_LINE_DASH_PX = {
    "solid": (0, 0),
    "dashed": (6, 4),
    "dotted": (2, 3),
    # Short marks with long spaces, laid across a line that stays whole --
    # the sleepers of a railway. The opposite rhythm to a dash, which is why
    # it cannot be expressed by tuning "dashed".
    "ticked": (2, 8),
}


def _dash(rule, what):
    """(dash length, gap length) in px. 0/0 means a solid stroke."""
    pattern = str(rule.get("pattern", "solid")).strip().lower()
    if pattern not in _LINE_DASH_PX:
        sys.exit(f"gen_mapstyle.py: {what}: pattern '{pattern}' is not one of "
                 f"{sorted(_LINE_DASH_PX)}")
    dash, gap = _LINE_DASH_PX[pattern]
    kind = {"solid": "Solid", "dashed": "Dashed", "dotted": "Dashed", "ticked": "Ticked"}[pattern]
    if rule.get("dash_px") is not None:
        dash = _round_px(rule["dash_px"], f"{what}.dash_px")
    if rule.get("gap_px") is not None:
        gap = _round_px(rule["gap_px"], f"{what}.gap_px")
    for value, field in ((dash, "dash_px"), (gap, "gap_px")):
        if value > 255:
            sys.exit(f"gen_mapstyle.py: {what}: {field} {value} does not fit a uint8_t")
    if dash > 0 and gap <= 0:
        sys.exit(f"gen_mapstyle.py: {what}: a dash with no gap is a solid line -- "
                 f"use pattern 'solid' or give gap_px above 0")
    return kind, dash, gap


_HATCH_PATTERN = {
    "/": "Diagonal",
    "\\": "AntiDiagonal",
    "-": "Horizontal",
    "|": "Vertical",
    "~": "Wave",
    "X": "Cross",
    "x": "Cross",
    "+": "Cross",
}


# mapstyle.json's `tone` names, mapped to MapAreaTone. A tone is a screen-space
# pixel pattern that reads as grey from arm's length -- what a built-up area
# wants. See the firmware's docs/map-style.md.
_TONES = {"stipple": "Stipple", "light": "Light", "dark": "Dark", "solid": "Solid"}


def _tone(rule, what):
    """MapAreaTone name for a rule with `fill: tone`, else "None"."""
    if rule.get("fill") != "tone":
        return "None"
    name = str(rule.get("tone", "")).strip().lower()
    if name not in _TONES:
        sys.exit(f"gen_mapstyle.py: {what}: fill is tone but tone '{name}' is not one of "
                 f"{sorted(_TONES)}")
    return _TONES[name]


def _hatch(rule, what):
    """(pattern enum name, spacing px) for a layer rule's fill.

    A rule with no `fill: hatch` draws no fill at all -- outline only, or
    nothing if the outline is 0 too. That is a legitimate style, so it is not
    an error.
    """
    if rule.get("fill") != "hatch":
        return "None", 0
    text = str(rule.get("hatch", "")).strip()
    if not text:
        sys.exit(f"gen_mapstyle.py: {what}: fill is hatch but no hatch pattern given")
    pattern = _HATCH_PATTERN.get(text[0])
    if pattern is None:
        sys.exit(f"gen_mapstyle.py: {what}: hatch '{text}' starts with a character this renderer "
                 f"has no pattern for (use one of {''.join(sorted(_HATCH_PATTERN))})")
    spacing = _round_px(rule.get("hatch_spacing_px", 0), f"{what}.hatch_spacing_px")
    if spacing <= 0:
        sys.exit(f"gen_mapstyle.py: {what}: hatch needs a hatch_spacing_px above 0 "
                 f"-- spacing 0 would be a solid fill, which 1-bit cannot afford")
    if spacing > 255:
        sys.exit(f"gen_mapstyle.py: {what}: hatch_spacing_px {spacing} does not fit a uint8_t")
    return pattern, spacing


def buildings(style):
    """(enabled, outline px, tone, hatch pattern, hatch spacing)."""
    layer = style.get("layers", {}).get("buildings", {})
    if not layer.get("enabled", False):
        return False, 0, "None", "None", 0
    rule = layer.get("rule", {})
    outline = _round_px(rule.get("outline_width", 0), "layers.buildings.rule.outline_width")
    tone = _tone(rule, "layers.buildings.rule")
    pattern, spacing = _hatch(rule, "layers.buildings.rule")
    if outline == 0 and pattern == "None" and tone == "None":
        sys.exit("gen_mapstyle.py: layers.buildings is enabled but draws neither an outline, a tone nor a "
                 "hatch -- that reads every building off the card to draw nothing. Disable the layer instead.")
    return True, outline, tone, pattern, spacing


def water(style):
    """(enabled, [width per water class], tone, hatch pattern, hatch spacing).

    Widths are per class now (river, stream, lake, unknown) -- the builder
    started writing a water class byte on 2026-08-05. Rules key on `class`, the
    same vocabulary the tile carries, not on raw OSM tags: matching `waterway:
    river` here would be a second vocabulary that cannot be checked against
    anything (docs/map-data-spec.md, "One vocabulary, not two").

    The area tone or hatch comes from whichever rule carries a `fill`; only the
    lake class ever arrives as a ring.
    """
    layer = style.get("layers", {}).get("water", {})
    widths = [0] * _WATER_SLOTS
    if not layer.get("enabled", False):
        return False, widths, ["Solid"] * _WATER_SLOTS, [0] * _WATER_SLOTS, [0] * _WATER_SLOTS, "None", "None", 0, False

    default_width = max(_round_px(layer.get("default", {}).get("width", 1), "layers.water.default.width"), 1)
    for class_id in _WATER_CLASS.values():
        widths[class_id] = default_width

    patterns_w = ["Solid"] * _WATER_SLOTS
    dashes = [0] * _WATER_SLOTS
    gaps = [0] * _WATER_SLOTS
    tone, pattern, spacing, white = "None", "None", 0, False
    for index, rule in enumerate(layer.get("rules", [])):
        what = f"layers.water.rules[{index}]"
        classes = rule.get("match", {}).get("class")
        if classes is None:
            sys.exit(f"gen_mapstyle.py: {what}: water rules must match on `class` "
                     f"({sorted(_WATER_CLASS)}), not on OSM tags -- the tile carries the class, not the tags")
        for name in classes:
            if name not in _WATER_CLASS:
                sys.exit(f"gen_mapstyle.py: {what}: unknown water class '{name}' "
                         f"(one of {sorted(_WATER_CLASS)})")
            width = max(_round_px(rule.get("width", default_width), f"{what}.width"), 1)
            if width > 255:
                sys.exit(f"gen_mapstyle.py: {what}: width {width}px does not fit a uint8_t")
            widths[_WATER_CLASS[name]] = 0 if rule.get("hidden", False) else width
            (patterns_w[_WATER_CLASS[name]], dashes[_WATER_CLASS[name]],
             gaps[_WATER_CLASS[name]]) = _dash(rule, what)
        # Water is the one layer that wants a tone *and* a pattern: a surface
        # dense enough to read as water, with waves knocked out of it in white.
        # Everywhere else `fill` picks one or the other, so both are read here
        # rather than switching on it.
        if rule.get("tone") and tone == "None":
            tone = _tone(dict(rule, fill="tone"), what)
        if rule.get("hatch") and pattern == "None":
            pattern, spacing = _hatch(dict(rule, fill="hatch"), what)
            if rule.get("hatch_white"):
                white = True
    return True, widths, patterns_w, dashes, gaps, tone, pattern, spacing, white


def landuse(style):
    """(enabled, [outline], [tone], [hatch], [spacing]) per landuse class.

    Forest and built-up share one tile layer and are drawn at different depths,
    so each class gets its own numbers and the renderer walks the layer once per
    class.
    """
    layer = style.get("layers", {}).get("landuse", {})
    outlines = [0] * _LANDUSE_SLOTS
    tones = ["None"] * _LANDUSE_SLOTS
    patterns = ["None"] * _LANDUSE_SLOTS
    spacings = [0] * _LANDUSE_SLOTS
    if not layer.get("enabled", False):
        return False, outlines, tones, patterns, spacings

    for index, rule in enumerate(layer.get("rules", [])):
        what = f"layers.landuse.rules[{index}]"
        classes = rule.get("match", {}).get("class")
        if classes is None:
            sys.exit(f"gen_mapstyle.py: {what}: landuse rules must match on `class` "
                     f"({sorted(_LANDUSE_CLASS)})")
        for name in classes:
            if name not in _LANDUSE_CLASS:
                sys.exit(f"gen_mapstyle.py: {what}: unknown landuse class '{name}' "
                         f"(one of {sorted(_LANDUSE_CLASS)})")
            class_id = _LANDUSE_CLASS[name]
            outlines[class_id] = _round_px(rule.get("outline_width", 0), f"{what}.outline_width")
            tones[class_id] = _tone(rule, what)
            patterns[class_id], spacings[class_id] = _hatch(rule, what)
            if outlines[class_id] == 0 and tones[class_id] == "None" and patterns[class_id] == "None":
                sys.exit(f"gen_mapstyle.py: {what}: class '{name}' draws neither an outline, a tone nor a "
                         f"hatch. Drop the rule instead -- an enabled layer is read off the card in full.")
    if not any(outlines) and not any(t != "None" for t in tones) and not any(p != "None" for p in patterns):
        sys.exit("gen_mapstyle.py: layers.landuse is enabled but no rule draws anything. Disable the layer.")
    return True, outlines, tones, patterns, spacings


def place_dot_diameter(style):
    places = style.get("layers", {}).get("places")
    if places is None:
        sys.exit("gen_mapstyle.py: layers.places missing")
    if not places.get("enabled", True):
        print("gen_mapstyle.py: layers.places.enabled is false -- no place dots will be drawn")
        return 0
    diameter = 2 * _round_px(places.get("dot_radius_px", 0), "layers.places.dot_radius_px")
    if diameter > 255:
        sys.exit(f"gen_mapstyle.py: place dot diameter {diameter}px does not fit a uint8_t")
    return diameter


def route(style):
    """(width, arrow_len, arrow_width) for layers.route, in device pixels.

    The route is told apart from the roads by width alone -- there is no colour
    on 1-bit e-ink -- so a width at or below the widest road is a style that
    hides the route inside the map. Warned about, not rejected: it is a legible
    thing to want while tuning, and the renderer honours whatever is here.
    """
    cfg = style.get("layers", {}).get("route")
    if cfg is None:
        sys.exit("gen_mapstyle.py: layers.route missing")
    if not cfg.get("enabled", True):
        print("gen_mapstyle.py: layers.route.enabled is false -- no route will be drawn")
        return 0, 0, 0
    width = _round_px(cfg.get("width", 0), "layers.route.width")
    arrow_len = _round_px(cfg.get("arrow_len_px", 0), "layers.route.arrow_len_px")
    arrow_width = _round_px(cfg.get("arrow_width_px", 0), "layers.route.arrow_width_px")
    for name, value in (("width", width), ("arrow_len_px", arrow_len),
                        ("arrow_width_px", arrow_width)):
        if value > 255:
            sys.exit(f"gen_mapstyle.py: layers.route.{name} {value}px does not fit a uint8_t")
    return width, arrow_len, arrow_width


def marker_anchor(style):
    device = style.get("device")
    if device is None:
        sys.exit("gen_mapstyle.py: device block missing")
    x = _round_px(device.get("marker_x_px", 0), "device.marker_x_px")
    y = _round_px(device.get("marker_y_px", 0), "device.marker_y_px")
    # Off-panel is allowed for tuning (MapViewport.h's marker ladder comment
    # says so), but it must still fit the int16_t it is stored in.
    if x > 32767 or y > 32767:
        sys.exit(f"gen_mapstyle.py: marker anchor {x},{y} does not fit an int16_t")
    return x, y


def _array(values, comments):
    """A C++ initialiser list, one value per line with its class name."""
    lines = ["    {"]
    for value, comment in zip(values, comments):
        lines.append(f"        {value},  // {comment}")
    lines.append("    },")
    return lines


def gen_cpp(widths, casings, patterns, dashes, gaps, buildings_px, water_px, landuse_px, dot_diameter, route_px, marker_x, marker_y,
            puck_px):
    id_to_name = {class_id: name for name, class_id in _CLASS_ID.items()}
    lines = [
        "#pragma once",
        "",
        f"// {_HEADER_NOTE}",
        "",
        '#include "MapStyle.h"',
        "",
        "// Designated initialisers on purpose: this file is generated, and a field",
        "// reordered in MapStyle.h must break the build rather than silently shift a",
        "// number into the wrong member (it did once, 2026-08-05).",
        "inline constexpr MapStyle kDefaultMapStyle = {",
        "    // Road width per MapClassId. 0 = not drawn.",
        "    .roadWidthPx =",
        "    {",
    ]
    for class_id in range(_CLASS_SLOTS):
        name = id_to_name.get(class_id, "(reserved)")
        lines.append(f"        {widths[class_id]},  // {class_id} {name}")
    lines += [
        "    },",
        "    // Casing per class, same indexing. 0 = solid black line.",
        "    .roadCasingPx =",
        "    {",
    ]
    for class_id in range(_CLASS_SLOTS):
        name = id_to_name.get(class_id, "(reserved)")
        lines.append(f"        {casings[class_id]},  // {class_id} {name}")
    lines += [
        "    },",
        "    // Line pattern per class. Order matters: designated initialisers",
        "    // must follow MapStyle.h.",
        "    .roadPattern =",
        "    {",
    ]
    for class_id in range(_CLASS_SLOTS):
        name = id_to_name.get(class_id, "(reserved)")
        lines.append(f"        MapLinePattern::{patterns[class_id]},  // {class_id} {name}")
    lines += [
        "    },",
        "    // Dash length per class, same indexing. 0 = a solid stroke.",
        "    .roadDashPx =",
        "    {",
    ]
    for class_id in range(_CLASS_SLOTS):
        name = id_to_name.get(class_id, "(reserved)")
        lines.append(f"        {dashes[class_id]},  // {class_id} {name}")
    lines += [
        "    },",
        "    .roadGapPx =",
        "    {",
    ]
    for class_id in range(_CLASS_SLOTS):
        name = id_to_name.get(class_id, "(reserved)")
        lines.append(f"        {gaps[class_id]},  // {class_id} {name}")
    radius, ring, arrow = puck_px
    b_enabled, b_outline, b_tone, b_pattern, b_spacing = buildings_px
    w_enabled, w_widths, w_patterns, w_dashes, w_gaps, w_tone, w_pattern, w_spacing, w_white = water_px
    l_enabled, l_outlines, l_tones, l_patterns, l_spacings = landuse_px
    water_names = [name for name, _ in sorted(_WATER_CLASS.items(), key=lambda kv: kv[1])]
    landuse_names = ["(unused)", "forest", "built_up", "(unused)"]
    lines += [
        "    },",
        f"    .buildingsEnabled = {'true' if b_enabled else 'false'},",
        f"    .buildingOutlinePx = {b_outline},",
        f"    .buildingTone = MapAreaTone::{b_tone},",
        f"    .buildingHatch = MapAreaFill::Pattern::{b_pattern},",
        f"    .buildingHatchSpacingPx = {b_spacing},",
        f"    .waterEnabled = {'true' if w_enabled else 'false'},",
        "    .waterLinePx =",
        *_array(w_widths, water_names),
        "    .waterPattern =",
        *_array([f"MapLinePattern::{p}" for p in w_patterns], water_names),
        "    .waterDashPx =",
        *_array(w_dashes, water_names),
        "    .waterGapPx =",
        *_array(w_gaps, water_names),
        f"    .waterTone = MapAreaTone::{w_tone},",
        f"    .waterHatch = MapAreaFill::Pattern::{w_pattern},",
        f"    .waterHatchSpacingPx = {w_spacing},",
        f"    .waterHatchWhite = {'true' if w_white else 'false'},",
        f"    .landuseEnabled = {'true' if l_enabled else 'false'},",
        "    .landuseOutlinePx =",
        *_array(l_outlines, landuse_names),
        "    .landuseTone =",
        *_array([f"MapAreaTone::{t}" for t in l_tones], landuse_names),
        "    .landuseHatch =",
        *_array([f"MapAreaFill::Pattern::{p}" for p in l_patterns], landuse_names),
        "    .landuseHatchSpacingPx =",
        *_array(l_spacings, landuse_names),
        f"    .placeDotDiameterPx = {dot_diameter},",
        f"    .routeWidthPx = {route_px[0]},",
        f"    .routeArrowLenPx = {route_px[1]},",
        f"    .routeArrowWidthPx = {route_px[2]},",
        f"    .markerXPx = {marker_x},",
        f"    .markerYPx = {marker_y},",
        f"    .puckRadiusPx = {radius},",
        f"    .puckRingPx = {ring},",
        f"    .puckArrowPx = {arrow},",
        "};",
        "",
    ]
    return "\n".join(lines)


def main(repo_root, style_path=None, output_path=None):
    if style_path is None:
        style_path = os.path.join(repo_root, "data", "mapstyle.json")
    if output_path is None:
        output_path = os.path.join(repo_root, "src", "activities", "map", "MapStyleDefaults.h")

    if not os.path.isfile(style_path):
        sys.exit(f"gen_mapstyle.py: {style_path} not found")

    with open(style_path) as f:
        style = json.load(f)

    widths, casings, patterns, dashes, gaps = road_widths(style)
    buildings_px = buildings(style)
    water_px = water(style)
    landuse_px = landuse(style)
    dot_diameter = place_dot_diameter(style)
    route_px = route(style)
    marker_x, marker_y = marker_anchor(style)
    puck_px = puck(style)

    drawn = sum(1 for w in widths if w)
    cased = sum(1 for c in casings if c)
    print(f"gen_mapstyle.py: {drawn} road classes drawn, widths {min(w for w in widths if w)}"
          f"..{max(widths)}px, {cased} cased, place dot {dot_diameter}px, marker {marker_x},{marker_y}, "
          f"puck r{puck_px[0]}/ring{puck_px[1]}/arrow{puck_px[2]}")
    print(f"gen_mapstyle.py: buildings {'on' if buildings_px[0] else 'off'} "
          f"(outline {buildings_px[1]}px, tone {buildings_px[2]}, hatch {buildings_px[3]}/{buildings_px[4]}px), "
          f"water {'on' if water_px[0] else 'off'} "
          f"(widths {water_px[1]}, dashes {water_px[3]}/{water_px[4]}, tone {water_px[5]}, "
          f"hatch {water_px[6]}/{water_px[7]}px{' white' if water_px[8] else ''})")
    widest_road = max(widths)
    if route_px[0] and route_px[0] <= widest_road:
        print(f"gen_mapstyle.py: warning -- route width {route_px[0]}px is not wider than the widest road "
              f"({widest_road}px); width is the only thing telling them apart on 1-bit e-ink")
    print(f"gen_mapstyle.py: route {route_px[0]}px wide, arrow {route_px[1]}x{route_px[2]}px")
    if landuse_px[0]:
        print(f"gen_mapstyle.py: landuse on -- forest tone {landuse_px[2][1]}/hatch {landuse_px[3][1]}, "
              f"built_up tone {landuse_px[2][2]}/hatch {landuse_px[3][2]}")
    else:
        print("gen_mapstyle.py: landuse off")

    with open(output_path, "w") as f:
        f.write(gen_cpp(widths, casings, patterns, dashes, gaps, buildings_px, water_px, landuse_px, dot_diameter, route_px, marker_x,
                        marker_y, puck_px))
    print(f"gen_mapstyle.py: wrote {output_path}")


